def said(fn, *args):
    buf = io.StringIO()
    with contextlib.redirect_stdout(buf):
        fn(*args)
    return buf.getvalue()


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('cmd')
    ap.add_argument('-p', '--project')
    ap.add_argument('--adapter')
    ap.add_argument('--src')
    ap.add_argument('--out')
    ap.add_argument('--prefix', default='T')
    ap.add_argument('--tm', action='append')
    ap.add_argument('--width', type=int, default=0)
    ap.add_argument('--long', type=int, default=100)
    ap.add_argument('--short', type=int, default=60)
    ap.add_argument('--speaker', action='store_true')
    ap.add_argument('--force', action='store_true')
    a = ap.parse_args()
    sys.stdout.reconfigure(encoding='utf-8')
    if a.cmd == 'selftest':
        return selftest()
    p = Prj(a.project)
    if a.cmd == 'extract':
        return cmd_extract(p, a)
    if a.adapter:
        ad = adapter(a.adapter)
        global TOKEN
        TOKEN = getattr(ad, 'TOKEN', TOKEN)
    _, rows, _ = load(p)
    if a.cmd in ('inject', 'verify', 'roundtrip'):
        return cmd_overlay(p, rows, a, a.cmd)
    if a.cmd == 'check':
        res, errs, pend, h = cmd_check(p, rows, a)
        return 1 if errs else 0
    fn = {'export': cmd_export, 'next': cmd_next, 'dupfill': cmd_dupfill, 'merge': cmd_merge,
          'import-held': cmd_import_held, 'resume-md': cmd_resume_md, 'seg-export': cmd_seg_export,
          'seg-build': cmd_seg_build, 'tpl': cmd_tpl}.get(a.cmd)
    if not fn:
        sys.exit(f'unknown command {a.cmd}')
    return fn(p, rows, a)


if __name__ == '__main__':
    sys.exit(main())
