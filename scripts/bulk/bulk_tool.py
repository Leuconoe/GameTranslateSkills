#!/usr/bin/env python3
"""bulk_tool.py - engine-agnostic bulk text harness (GameTranslateSkills shared tool).

  python -I bulk_tool.py <cmd> -p <title _work/TID dir> [options]

  extract   --adapter A [--src DIR] [--prefix ID] [--force]  adapter.extract -> translation_manifest.tsv (refuses overwrite)
  export    [--speaker]          exports/source/bulk_source.txt: n<TAB>source (n = 1-based manifest row); first row of
                                 each unique (name-row?, source); non-translatable rows (digits/symbols/IDs/Korean) skipped
  next                           resume point: first export line whose n is not in a translator part yet
  dupfill   [--tm MANIFEST ...]  out/PZ_dupfill.tsv (same-speaker donor preferred; cross-speaker fills listed in
                                 dupfill_xspk.tsv for review) + out/PZ_tm.tsv (exact source from sibling-title manifests)
  check     [--width N]          validate every out/P*.tsv row (tokens, line breaks, brackets, JP residue, line width)
  seg-export [--long N] [--force] / seg-build   segment TM for long templated rows (glossary-rules rule 10)
  merge     [--width N]          ONE atomic manifest write + merge_log (refuses on any error or pending row)
  import-held                    30_translation/text/HELD_FOR_USER.tsv (id, text): text != source -> translation
  resume-md [--force]            write a <=40-line 30_translation/RESUME.md skeleton
  inject / verify / roundtrip --adapter A --out NEWDIR   overlay write; verify/roundtrip read every row back by key
  selftest

Parts: out/P*.tsv lines `n<TAB>ko` (`<KEEP>` keeps the source). PZ_*/PS_* parts are generated by this tool.
Line breaks: each row keeps its own source form (engine escape `\\n` vs escaped `\\\\n`); parts may use either.
Held rows: ids listed in HELD_FOR_USER.tsv (+ legacy HELD_ROWS.tsv `first<TAB>last` n ranges) stay source until import-held.
Adapter (python file): SRC_REL; extract(src_root) -> iter of dict(source_file, source_key, ja, notes[, speaker]);
  inject(rows, src_root, out_root) -> [rel paths] writing row['value']; read(roots, rows) -> [value at each row key]
  (roots = [overlay, src_root], first existing file wins; never filter by language); optional TOKEN regex.
"""
import argparse
import collections
import hashlib
import importlib.util
import os
import re
import sys
import tempfile
import unicodedata
from pathlib import Path

JP = re.compile(r'[぀-ヿ㐀-鿿ｦ-ﾟ々〆、。・]')
LETTER = re.compile(r'[A-Za-z぀-ヿ㐀-鿿ｦ-ﾟ]')
IDLIKE = re.compile(r'^(?=.*[0-9_./])[A-Za-z0-9_./:#-]+$')
HANGUL = re.compile(r'[가-힣]')
TOKEN = re.compile(r'<[^<>]*>|\{\d+\}|%%C|%C|%[-+ 0-9.]*[sdfx]|\$\{[^}]*\}|\[[^\[\]\u3040-\u9fff\uac00-\ud7a3]*\]')
BR = re.compile(r'\\\\n|\\n')  # escaped form (3 chars) first, then the 2-char engine escape
PAIRS = ('「」', '『』', '（）', '【】')
QUOTES = '「」『』“”‘’"'
ESC = re.compile(r'\\\\|\\.')
GEN = ('PZ_dupfill.tsv', 'PZ_tm.tsv', 'PS_seg.tsv')
NAME_KIND = re.compile(r'speaker|name|chara', re.I)
KOPOL = re.compile(r'(요|니다|니까|죠|세요)[!?~.…―\s」』）)]*$')


# ---------- project paths / manifest ----------
class Prj:
    def __init__(self, root):
        self.root = Path(root)
        t = self.root / '30_translation'
        self.man = t / 'text' / 'translation_manifest.tsv'
        self.src = t / 'exports' / 'source' / 'bulk_source.txt'
        self.segsrc = t / 'exports' / 'source' / 'seg_source.txt'
        self.bulk = t / 'text' / 'batches' / 'bulk'
        self.out, self.oseg = self.bulk / 'out', self.bulk / 'out_seg'
        self.held_rows, self.hfu = self.bulk / 'HELD_ROWS.tsv', t / 'text' / 'HELD_FOR_USER.tsv'
        self.log, self.resume = t / 'text' / 'batches' / 'merge_log.tsv', t / 'RESUME.md'


def w_atomic(path, text, bom=False):
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_name(path.name + '.tmp')
    with open(tmp, 'w', encoding='utf-8-sig' if bom else 'utf-8', newline='\n') as fh:
        fh.write(text)
        fh.flush()
        os.fsync(fh.fileno())
    os.replace(tmp, path)


def load(p):
    raw = p.man.read_bytes()
    lines = raw.decode('utf-8-sig').split('\n')
    hdr = lines[0].rstrip('\r').split('\t')
    for c in ('id', 'ja', 'target_ko', 'status', 'notes'):
        assert c in hdr, f'manifest header lacks {c}'
    rows = [dict(zip(hdr, l.rstrip('\r').split('\t'))) for l in lines[1:] if l.strip()]
    return hdr, rows, raw.startswith(b'\xef\xbb\xbf')


def save(p, hdr, rows, bom):
    w_atomic(p.man, '\t'.join(hdr) + '\n' + ''.join('\t'.join(r.get(h, '') for h in hdr) + '\n' for r in rows), bom)
    return hashlib.sha256(p.man.read_bytes()).hexdigest()


def log(p, text):
    p.log.parent.mkdir(parents=True, exist_ok=True)
    with open(p.log, 'a', encoding='utf-8', newline='\n') as fh:
        fh.write(text + '\n')


def kind(r):
    return r['notes'].split(';')[0]


def spk(r):
    m = re.search(r'spk=([^;]*)', r['notes'])
    return m.group(1).split('|')[0] if m else ''


def key(r):
    return (bool(NAME_KIND.search(kind(r))), r['ja'])


def translatable(s):
    t = TOKEN.sub('', BR.sub('', s)).strip()
    return bool(LETTER.search(t)) and not IDLIKE.match(t)


def held(p, rows):
    out = set()
    if p.held_rows.exists():
        for l in p.held_rows.read_text(encoding='utf-8-sig').split('\n')[1:]:
            g = l.rstrip('\r').split('\t')
            if len(g) >= 2 and g[0].isdigit() and g[1].isdigit():
                out.update(range(int(g[0]), int(g[1]) + 1))
    if p.hfu.exists():
        ids = {l.split('\t')[0] for l in p.hfu.read_text(encoding='utf-8-sig').split('\n')[1:] if l.strip()}
        out.update(n for n, r in enumerate(rows, 1) if r['id'] in ids)
    return out


def pending(rows, h):
    return [n for n, r in enumerate(rows, 1) if r['status'] == 'new' and n not in h and translatable(r['ja'])]


# ---------- line breaks / checks ----------
def fix_br(ja, ko):
    """rewrite ko breaks into the row's own source form when the source uses exactly one form."""
    forms = set(BR.findall(ja))
    if len(forms) == 1:
        f = forms.pop()
        return BR.sub(lambda m: f, ko)
    return ko


def width(s):
    return sum(2 if unicodedata.east_asian_width(c) in 'WF' else 1 for c in s)


def balanced(s, o, c):
    d = 0
    for ch in s:
        d += (ch == o) - (ch == c)
        if d < 0:
            return False
    return d == 0


def check_row(ja, ko, kd='', maxw=0, tok=None):
    tok = tok or TOKEN
    if not ko.strip():
        return ['empty']
    if re.search(r'[\t\r\n]', ko):
        return ['control char']
    errs = []
    if tok.findall(ja) != tok.findall(ko):
        errs.append(f'tokens {tok.findall(ja)} != {tok.findall(ko)}')
    if BR.findall(ja) != BR.findall(ko):
        errs.append(f'line breaks {len(BR.findall(ja))} != {len(BR.findall(ko))} (or form)')
    else:
        for a, b in zip(BR.split(ja)[1:], BR.split(ko)[1:]):
            if a.startswith('　') != b.startswith('　'):
                errs.append('leading 　 after break differs')
                break
    if not set(ESC.findall(BR.sub('', ko))) <= set(ESC.findall(BR.sub('', ja))):
        errs.append('stray backslash escape')
    # Quote substitution is allowed: 「」『』 may become “” ‘’ "" in Korean. Only the total number of quote marks must match.
    q = lambda s: sum(s.count(x) for x in QUOTES)  # noqa: E731
    quotes_swapped = any(x in ko for x in '“”‘’"') and q(ja) == q(ko)
    if q(ja) != q(ko):
        errs.append('quote count (「」『』“”‘’")')
    for o, c in PAIRS:
        if quotes_swapped and o in '「『':
            continue
        n = lambda s, x: s.count(x) + (s.count('(' if x == '（' else ')') if x in '（）' else 0)  # noqa: E731
        if o in '「『' and q(ja) != q(ko):
            continue  # already reported as a quote-count error
        if (n(ja, o), n(ja, c)) != (n(ko, o), n(ko, c)):
            errs.append(f'bracket count {o}{c}')
        elif o != '（' and balanced(ja, o, c) and not balanced(ko, o, c):
            errs.append(f'bracket balance {o}{c}')
    if JP.search(tok.sub('', ko)):
        errs.append(f'JP residue {JP.findall(tok.sub("", ko))[:3]}')
    if NAME_KIND.search(kd) and tok.findall(ko):
        errs.append('tag in name row')
    if maxw:
        w = max(width(tok.sub('', x)) for x in BR.split(ko))
        if w > maxw:
            errs.append(f'line width {w} > {maxw}')
    return errs


def read_parts(p, generated=True):
    got = []
    for f in sorted(p.out.glob('P*.tsv')):
        if f.name in GEN and not generated:
            continue
        for i, l in enumerate(f.read_text(encoding='utf-8-sig').split('\n'), 1):
            if l.strip():
                got.append((f'{f.name}:{i}', l.rstrip('\r').split('\t')))
    return got


def collect(p, rows, maxw=0, tok=None):
    res, errs, h = {}, [], held(p, rows)
    for where, g in read_parts(p):
        if len(g) != 2 or not g[0].isdigit() or not 1 <= int(g[0]) <= len(rows):
            errs.append(f'{where}: bad line {g[:2]}')
            continue
        n, r = int(g[0]), rows[int(g[0]) - 1]
        if n in res:
            errs.append(f'{where}: n {n} duplicate')
        elif n in h:
            errs.append(f'{where}: n {n} is held')
        elif r['status'] != 'new':
            errs.append(f'{where}: n {n} status {r["status"]}')
        else:
            ko = g[1] if g[1] == '<KEEP>' else fix_br(r['ja'], g[1])
            res[n] = ko
            if ko != '<KEEP>':
                errs += [f'{where}: n {n} {e}' for e in check_row(r['ja'], ko, kind(r), maxw, tok)]
    return res, errs, h


# ---------- commands ----------
def cmd_export(p, rows, a):
    h, seen, lines = held(p, rows), set(), []
    for n, r in enumerate(rows, 1):
        if r['status'] == 'new' and n not in h and translatable(r['ja']) and key(r) not in seen:
            seen.add(key(r))
            lines.append(f"{n}\t{spk(r)}\t{r['ja']}\n" if a.speaker else f"{n}\t{r['ja']}\n")
    w_atomic(p.src, ''.join(lines))
    skipped = sum(r['status'] == 'new' and not translatable(r['ja']) for r in rows)
    print(f'export {len(lines)} unique rows -> {p.src}; non-translatable skipped {skipped}; held {len(h)}')


def cmd_next(p, rows, a):
    done = {int(g[0]) for _, g in read_parts(p, generated=False) if g and g[0].isdigit()} | held(p, rows)
    ns = [int(l.split('\t', 1)[0]) for l in p.src.read_text(encoding='utf-8').split('\n') if l]
    left = [i for i, n in enumerate(ns) if n not in done]
    print(f'next line {left[0] + 1} n {ns[left[0]]}; remaining {len(left)}/{len(ns)}' if left
          else f'all {len(ns)} export rows done -> dupfill, check, merge')


def load_tm(paths):
    tm = {}
    for f in paths or ():
        lines = Path(f).read_text(encoding='utf-8-sig').split('\n')
        hdr = lines[0].rstrip('\r').split('\t')
        for l in lines[1:]:
            r = dict(zip(hdr, l.rstrip('\r').split('\t')))
            if r.get('target_ko') and r.get('status', '').startswith('translated'):
                tm.setdefault(r['ja'], r['target_ko'])
    return tm


def cmd_dupfill(p, rows, a):
    h, donors = held(p, rows), collections.defaultdict(list)
    have = {}
    for _, g in read_parts(p, generated=False):
        if len(g) == 2 and g[0].isdigit() and 1 <= int(g[0]) <= len(rows):
            have.setdefault(int(g[0]), g[1])
    for n in sorted(have):
        donors[key(rows[n - 1])].append(n)
    tm, dup, tml, xs = load_tm(a.tm), [], [], ['id\tspeaker\tdonor_id\tdonor_speaker\tregister\tja\tko']
    for n, r in enumerate(rows, 1):
        if r['status'] != 'new' or n in have or n in h or not translatable(r['ja']):
            continue
        d = donors.get(key(r))
        if d:
            m = next((x for x in d if spk(rows[x - 1]) == spk(r)), d[0])
            ko = have[m] if have[m] == '<KEEP>' else fix_br(r['ja'], have[m])
            dup.append(f'{n}\t{ko}\n')
            if spk(rows[m - 1]) != spk(r) and HANGUL.search(ko):
                reg = 'polite' if any(KOPOL.search(x.strip()) for x in BR.split(ko)) else 'casual'
                xs.append(f"{r['id']}\t{spk(r)}\t{rows[m - 1]['id']}\t{spk(rows[m - 1])}\t{reg}\t{r['ja']}\t{ko}")
        elif r['ja'] in tm and not check_row(r['ja'], fix_br(r['ja'], tm[r['ja']]), kind(r)):
            tml.append(f"{n}\t{fix_br(r['ja'], tm[r['ja']])}\n")
    w_atomic(p.out / 'PZ_dupfill.tsv', ''.join(dup))
    w_atomic(p.out / 'PZ_tm.tsv', ''.join(tml))
    w_atomic(p.bulk / 'dupfill_xspk.tsv', '\n'.join(xs) + '\n')
    print(f'dupfill {len(dup)} rows (cross-speaker {len(xs) - 1} -> dupfill_xspk.tsv); tm {len(tml)} rows '
          f'from {len(tm)} sibling entries')


def cmd_check(p, rows, a, quiet=False):
    res, errs, h = collect(p, rows, a.width)
    pend = [n for n in pending(rows, h) if n not in res]
    if errs:
        print('\n'.join(errs[:80]))
    if not quiet:
        print(f'check rows={len(res)} errors={len(errs)} pending={len(pend)} {pend[:10]} held={len(h)}')
    return res, errs, pend, h


def cmd_merge(p, rows, a):
    hdr, rows, bom = load(p)
    res, errs, pend, h = cmd_check(p, rows, a, quiet=True)
    if errs or pend:
        sys.exit(f'refuse merge: errors {len(errs)}, pending {len(pend)} {pend[:10]} (run dupfill / fix parts)')
    nt = 0
    for n, ko in res.items():
        r = rows[n - 1]
        r['target_ko'], r['status'] = ('' if ko == '<KEEP>' else ko), 'translated'
        if ko == '<KEEP>':
            r['notes'] += ';keep_source'
    for n, r in enumerate(rows, 1):
        if r['status'] == 'new' and not translatable(r['ja']):
            r['status'], r['notes'], nt = 'translated', r['notes'] + ';keep_source;nontrans', nt + 1
    sha = save(p, hdr, rows, bom)
    log(p, f'BULK\t{len(res)} rows\tnontrans={nt}\tQA_OK\theld={len(h)}\t{sha}')
    print(f'merged {len(res)} + nontrans {nt} | translated {sum(r["status"] == "translated" for r in rows)}/'
          f'{len(rows)} | held {len(h)} | sha256 {sha}')


def cmd_import_held(p, rows, a):
    hdr, rows, bom = load(p)
    if not p.hfu.exists():
        return print('no HELD_FOR_USER.tsv (0 held)')
    by = {r['id']: r for r in rows}
    edits, errs = [], []
    for i, l in enumerate(p.hfu.read_text(encoding='utf-8-sig').split('\n')[1:], 2):
        g = l.rstrip('\r').split('\t')
        if not l.strip():
            continue
        r = by.get(g[0])
        if r is None or len(g) != 2:
            errs.append(f'line {i}: unknown id / not 2 columns')
            continue
        if not g[1].strip() or g[1] == r['ja']:
            continue
        ko = fix_br(r['ja'], g[1])
        e = check_row(r['ja'], ko, kind(r), a.width)
        errs += [f'line {i} {g[0]}: {x}' for x in e]
        edits.append((r, ko))
    if errs:
        print('\n'.join(errs[:80]))
        sys.exit(f'refuse import-held: {len(errs)} errors; nothing written')
    for r, ko in edits:
        r['target_ko'], r['status'], r['notes'] = ko, 'translated', r['notes'] + ';held_user'
    sha = save(p, hdr, rows, bom)
    log(p, f'HELD\t{len(edits)} rows (HELD_FOR_USER.tsv)\tQA_OK\t\t{sha}')
    print(f'import-held {len(edits)} rows | sha256 {sha}')


def cmd_resume_md(p, rows, a):
    if p.resume.exists() and not a.force:
        sys.exit(f'refuse: {p.resume} exists (use --force)')
    c = collections.Counter(spk(r) for r in rows if spk(r))
    me = f'python -I "{Path(__file__).resolve()}" {{}} -p "{p.root}"'
    lines = [f'# RESUME - {p.root.name}', '',
             '## 화자 말투 (상위 화자; 채울 것)', *[f'- {s} ({n}행): ' for s, n in c.most_common(8)], '',
             '## 반드시 지킬 용어 (최대 30개; 채울 것)', '- 원문 → 번역', '',
             '## 원문·파트', f'- 원문: `{p.src}` (n<TAB>원문)', f'- 파트: `{p.out}\\P<첫n>.tsv` (n<TAB>번역, `<KEEP>` = 원문 유지)',
             f'- 재개 지점: `{me.format("next")}`',
             '- 보류: `30_translation/text/HELD_FOR_USER.tsv` (id<TAB>text) 끝에 덧붙임. 0행이면 만들지 않음.', '',
             '## 마지막 1회', f'1. `{me.format("dupfill")}`  (자매 타이틀 TM: `--tm <manifest>`)',
             f'2. `{me.format("check")}` → 실패 행만 수정',
             f'3. `{me.format("merge")}`', f'4. `{me.format("verify")} --adapter <A> --out <새 폴더>`', '',
             '## State', '- 실행 | 행 수 / 토큰 | 다음 지점']
    assert len(lines) <= 40
    w_atomic(p.resume, '\n'.join(lines) + '\n')
    print(f'resume-md {len(lines)} lines -> {p.resume}')


# ---------- segment TM (glossary-rules rule 10) ----------
SEP = re.compile(r'(\\\\n|\\n|<[^<>]*>)')
NUM = re.compile(r'[0-9０-９]+')
FW = str.maketrans('０１２３４５６７８９！？～〜・', '0123456789!?~~·')
OPEN, CLOSE, END = '「『（(【', '」』）)】', '。！？!?'


def split_sent(s):
    out, cur, d = [], '', 0
    for i, c in enumerate(s):
        cur += c
        d += (c in OPEN) - (c in CLOSE)
        if d <= 0 and (c in END or (c == '.' and (i + 1 == len(s) or s[i + 1] == ' '))):
            out.append(cur)
            cur = ''
    out.append(cur)
    out = [x.strip(' 　') if i else x.rstrip(' 　') for i, x in enumerate(out)]
    return [x for x in out if x] or ['']


def nums(s):
    return [x.translate(FW) for x in NUM.findall(s)]


def subst(rep, ko, seg):
    if rep == seg:
        return ko
    a, b, k = nums(rep), nums(seg), re.findall(r'[0-9]+', ko)
    if k == a:
        it = iter(b)
        return re.sub(r'[0-9]+', lambda m: next(it), ko)
    if sorted(k) == sorted(a) and len(set(a)) == len(a):
        mp = dict(zip(a, b))
        return re.sub(r'[0-9]+', lambda m: mp[m.group()], ko)
    return None


class TM:
    def __init__(self):
        self.exact, self.norm = {}, {}

    def add(self, ja, ko, exact_only=False):
        self.exact[ja] = ko
        if not exact_only:
            self.norm.setdefault(NUM.sub('#', ja), (ja, ko))

    def get(self, seg):
        if not JP.search(seg):
            return seg.translate(FW)
        if seg in self.exact:
            return self.exact[seg]
        r = self.norm.get(NUM.sub('#', seg))
        return subst(*r, seg) if r else None


def assemble(ja, tm, miss):
    p = SEP.split(ja)
    out = []
    for t in p[0::2]:
        ko = []
        for s in split_sent(t):
            k = tm.get(s)
            if k is None:
                miss.append(s)
            ko.append(k or '')
        out.append(' '.join(ko))
    return ''.join(x for pair in zip(out, p[1::2] + ['']) for x in pair)


def seg_errs(ja, ko):
    e = [] if SEP.findall(ja) == SEP.findall(ko) else ['breaks/tags']
    if TOKEN.findall(ja) != TOKEN.findall(ko):
        e.append('tokens')
    kd = collections.Counter(re.findall(r'[0-9]+', ko))
    if collections.Counter(nums(ja)) - kd:
        e.append('numbers')
    return e + [x for x in check_row(ja, ko) if x.startswith(('bracket', 'JP'))]


def seg_targets(p, rows, a):
    src = {int(l.split('\t', 1)[0]): rows[int(l.split('\t', 1)[0]) - 1]['ja']
           for l in p.src.read_text(encoding='utf-8').split('\n') if l}
    done = {int(g[0]): g[1] for _, g in read_parts(p) if len(g) == 2 and g[0].isdigit()
            and not _.startswith('PS_seg.tsv:')}
    h = held(p, rows)
    return src, done, [(n, ja) for n, ja in src.items() if n not in done and n not in h and len(ja) > a.long]


def cmd_seg_export(p, rows, a):
    if p.segsrc.exists() and not a.force:
        sys.exit(f'refuse: {p.segsrc} exists (segment ids must stay stable; --force)')
    src, done, target = seg_targets(p, rows, a)
    tm, seeded = TM(), 0
    for n, ko in done.items():
        ja = src.get(n)
        if not ja or ko == '<KEEP>':
            continue
        jp, kp = SEP.split(ja), SEP.split(fix_br(ja, ko))
        if jp[1::2] != kp[1::2]:
            continue
        for x, y in zip(jp[0::2], kp[0::2]):
            sa = split_sent(x)
            sb = [y.strip(' ')] if len(sa) == 1 else [z for z in re.split(r'(?<=[.!?]) +', y) if z]
            if len(sa) == len(sb):
                for s, k in zip(sa, sb):
                    if JP.search(s) and s not in tm.exact and not JP.search(k):
                        tm.add(s, k)
                        seeded += 1
    seen, todo, tot = set(), [], collections.Counter()
    for n, ja in target:
        for t in SEP.split(ja)[0::2]:
            for s in split_sent(t):
                if JP.search(s):
                    tot[s] += 1
                    if tm.get(s) is None and NUM.sub('#', s) not in seen:
                        seen.add(NUM.sub('#', s))
                        todo.append(s)
    used = {s: tm.exact[s] for s in tot if s in tm.exact}
    w_atomic(p.oseg / 'S_seed.tsv', ''.join(f'=\t{x}\t{y}\n' for x, y in used.items()))
    w_atomic(p.segsrc, ''.join(f'{k}\t{s}\n' for k, s in enumerate(todo, 1)))
    print(f'seg-export rows {len(target)}; unique segs {len(tot)}; seeded {seeded} (used {len(used)}); '
          f'to translate {len(todo)} -> {p.segsrc} (answers: out_seg/*.tsv k<TAB>ko or =<TAB>ja<TAB>ko)')


def cmd_seg_build(p, rows, a):
    src, done, target = seg_targets(p, rows, a)
    segsrc = dict(l.split('\t', 1) for l in p.segsrc.read_text(encoding='utf-8').split('\n') if l)
    tm = TM()
    for f in sorted(p.oseg.glob('*.tsv')):
        for l in f.read_text(encoding='utf-8-sig').split('\n'):
            g = l.rstrip('\r').split('\t')
            if len(g) == 3 and g[0] == '=':
                tm.add(g[1], g[2], exact_only=f.name != 'S_seed.tsv')
            elif len(g) == 2 and g[0] in segsrc:
                tm.add(segsrc[g[0]], g[1])
    ok, bad, partial = [], [], 0
    for n, ja in target:
        miss = []
        ko = assemble(ja, tm, miss)
        if miss:
            partial += 1
            continue
        e = seg_errs(ja, ko)
        (bad if e else ok).append((n, ko, e))
    w_atomic(p.out / 'PS_seg.tsv', ''.join(f'{n}\t{ko}\n' for n, ko, _ in ok))
    w_atomic(p.bulk / 'seg_fail.txt', ''.join(f'#{n}\t{",".join(e)}\t{ko}\n' for n, ko, e in bad))
    print(f'seg-build target {len(target)}: built {len(ok)} -> PS_seg.tsv; check-fail {len(bad)} -> seg_fail.txt; '
          f'incomplete {partial}')


# ---------- adapter: extract / inject / verify / roundtrip ----------
def adapter(path):
    spec = importlib.util.spec_from_file_location(Path(path).stem, path)
    m = importlib.util.module_from_spec(spec)
    sys.path.insert(0, str(Path(path).resolve().parent))
    spec.loader.exec_module(m)
    return m


def src_root(p, a, ad):
    return Path(a.src) if a.src else p.root / ad.SRC_REL


def cmd_extract(p, a):
    ad = adapter(a.adapter)
    if p.man.exists() and p.man.stat().st_size > 200 and not a.force:
        sys.exit(f'refuse: {p.man} exists (frozen source; --force only for a deliberate re-baseline)')
    rows = []
    for n, r in enumerate(ad.extract(src_root(p, a, ad)), 1):
        assert not re.search(r'[\t\r\n]', r['ja']), (r['source_file'], r['source_key'])
        notes = r.get('notes', '') + (f";spk={r['speaker']}" if r.get('speaker') else '')
        rows.append({'id': f'{a.prefix}{n:06d}', 'source_file': r['source_file'], 'source_key': r['source_key'],
                     'ja': r['ja'], 'en': '', 'target_ko': '', 'status': 'new', 'notes': notes})
    sha = save(p, ['id', 'source_file', 'source_key', 'ja', 'en', 'target_ko', 'status', 'notes'], rows, False)
    print(f'extract rows={len(rows)} unique={len({r["ja"] for r in rows})} sha256={sha}')


def cmd_overlay(p, rows, a, mode):
    ad = adapter(a.adapter)
    sr, out = src_root(p, a, ad), Path(a.out)
    if out.exists():
        sys.exit(f'refuse: {out} exists (each build gets a new dir)')
    for r in rows:
        r['value'] = r['ja'] if mode == 'roundtrip' else (r['target_ko'] or r['ja'])
    files = ad.inject(rows, sr, out)
    if mode == 'inject':
        return print(f'inject files={len(files)} -> {out}')
    got = ad.read([out, sr], rows)
    bad = [(r['id'], r['value'], v) for r, v in zip(rows, got) if v != r['value']]
    same = sum((out / f).read_bytes() == (sr / f).read_bytes() for f in files)
    for b in bad[:20]:
        print('MISMATCH', *b, sep='\t')
    print(f'{mode} rows={len(rows)} mismatch={len(bad)} files={len(files)} byte_identical={same}')
    return 1 if bad else 0


# ---------- selftest ----------
def selftest():
    assert fix_br('a\\nb', 'x\\\\ny') == 'x\\ny' and fix_br('a\\\\nb', 'x\\ny') == 'x\\\\ny'
    assert fix_br('a\\nb\\\\nc', 'x\\\\ny') == 'x\\\\ny'  # mixed source forms: untouched
    assert check_row('「あ」\\n　い%s', '「가」\\n　나%s') == []
    assert check_row('「あ」と『い』', '"가"와 \'나\'') != []          # apostrophes are not quote substitutes
    assert check_row('「あ」と『い』', '"가"와 "나"') == []             # quote substitution allowed
    assert check_row('「あ」と『い』', '“가”와 ‘나’') == []
    assert check_row('「あ」', '"가') != []                             # a quote mark lost
    assert check_row('あ\\nい', '가 나') and check_row('あ<b>', '가') and check_row('あ', '가あ')
    assert check_row('あ', '가가가가', maxw=6) and not translatable('123') and not translatable('ui_01')
    assert not translatable('한국어') and translatable('OK') and translatable('あ')
    tm = TM()
    tm.add('※5月1日まで。', '※5월 1일까지.')
    assert tm.get('※12月31日まで。') == '※12월 31일까지.' and tm.get('★５') == '★5'
    assert split_sent('A。「B。C」D。E') == ['A。', '「B。C」D。', 'E']
    tm.add('あ。', 'a.')
    tm.add('い', 'b')
    miss = []
    assert assemble('あ。い\\n<x>あ。', tm, miss) == 'a. b\\n<x>a.' and not miss
    with tempfile.TemporaryDirectory() as d:
        p = Prj(d)
        hdr = ['id', 'source_file', 'source_key', 'ja', 'en', 'target_ko', 'status', 'notes']
        src = [('こんにちは\\n元気？', 'dlg;spk=A'), ('こんにちは\\n元気？', 'dlg;spk=B'), ('123', 'ui'),
               ('秘密', 'dlg;spk=A'), ('長い文。' * 30 + '\\n' + '第3回。' * 5, 'tsv'), ('風太郎', 'speaker'),
               ('風太郎', 'dlg;spk=A')]
        rows = [dict(zip(hdr, (f'T{i}', 'f', str(i), ja, '', '', 'new', nt))) for i, (ja, nt) in enumerate(src, 1)]
        save(p, hdr, rows, True)
        w_atomic(p.hfu, 'id\ttext\nT4\t秘密\n', bom=True)
        ns = argparse.Namespace(speaker=False, tm=None, width=0, long=100, force=False)
        cmd_export(p, rows, ns)
        assert [l.split('\t')[0] for l in p.src.read_text(encoding='utf-8').split('\n') if l] == ['1', '5', '6', '7']
        w_atomic(p.out / 'P000001.tsv', '1\t안녕\\\\n잘 지내?\n6\t후타로\n7\t후타로\n')
        cmd_seg_export(p, rows, ns)
        segs = dict(l.split('\t') for l in p.segsrc.read_text(encoding='utf-8').split('\n') if l)
        assert set(segs.values()) == {'長い文。', '第3回。'}, segs
        k = {v: k for k, v in segs.items()}
        w_atomic(p.oseg / 'S1.tsv', f"{k['長い文。']}\t긴 문장.\n{k['第3回。']}\t제3회.\n")
        cmd_seg_build(p, rows, ns)
        cmd_dupfill(p, rows, ns)
        assert p.out.joinpath('PZ_dupfill.tsv').read_text(encoding='utf-8') == '2\t안녕\\n잘 지내?\n'
        assert p.bulk.joinpath('dupfill_xspk.tsv').read_text(encoding='utf-8').count('\n') == 2
        _, rows, _ = load(p)
        cmd_merge(p, rows, ns)
        _, rows, bom = load(p)
        assert bom and [r['status'] for r in rows] == ['translated'] * 3 + ['new'] + ['translated'] * 3
        assert rows[0]['target_ko'] == '안녕\\n잘 지내?' and rows[2]['notes'].endswith('nontrans')
        assert rows[4]['target_ko'].startswith('긴 문장. 긴 문장.') and '\\n제3회.' in rows[4]['target_ko']
